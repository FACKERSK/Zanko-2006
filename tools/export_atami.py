#!/usr/bin/env python3
"""Export concept map 6 (tools/atami.py, mirrored Atami) as the game's fixed town: zk_design.h.
World = design + (TX, TZ) metres. Every lot drawn on the map becomes a building: the largest axis-aligned rectangle
that fits inside it (the engine builds walls along the axes), its front facing the nearest street."""
import sys, os, math
import numpy as np
from shapely.geometry import Polygon, LineString, Point, box, MultiPolygon
from shapely.ops import unary_union, polylabel
import shapely
HERE = os.path.dirname(os.path.abspath(__file__))
TX, TZ = -20.0, -20.0
rec = []
def hook(orig):
    def lots(block, rng, target):
        out = orig(block, rng, target); rec.extend(out); return out
    return lots
NS = {"LOTS_HOOK": hook, "__file__": os.path.join(HERE, "atami.py")}
sys.argv = ["atami.py", "/tmp/claude-0/maps"]
exec(compile(open(os.path.join(HERE, "atami.py"), encoding="utf-8").read(), "atami.py", "exec"), NS)
c, rail, stn, bridges = NS["c"], NS["rail"], NS["stn"], NS["bridges"]
W = lambda x, y: (x + TX, y + TZ)
def wl(g, step):
    L = g.length; n = max(2, int(L / step) + 1); return [W(*g.interpolate(L * k / (n - 1)).coords[0]) for k in range(n)]
def arr(name, pts):
    return f"static const float {name}[][2] = {{" + ", ".join("{%.2ff, %.2ff}" % p for p in pts) + f"}};\n#define {name.upper()}_N {len(pts)}\n"
out = ["// zk_design.h - generated by tools/export_atami.py from concept map 6 (mirrored Atami). Do not edit by hand.\n",
       f"// world = design + ({TX}, {TZ}) metres\n"]
# ---- legacy grid symbols: the grid is gone (every block GONE); kept so older code paths compile and do nothing
out.append("static const unsigned char designKind[12][12] = {" + ", ".join("{" + ", ".join(["1"] * 12) + "}" for _ in range(12)) + "};\n")
out.append("#define DS_PLAZA 6\n#define SUB_ROW 0\n#define SUB_X0 0.0f\n#define SUB_X1 0.0f\nstatic const int subCols[3] = {0, 0, 0};\nstatic const int kobanB[2] = {-9, -9};\nstatic const int konbiniB[5][2] = {{-9, -9}, {-9, -9}, {-9, -9}, {-9, -9}, {-9, -9}};\n")
# ---- town outline (the land side of the coast road is part of it; the C side cuts the river and the strip seaward of the road)
water = unary_union([c.sea] + c.water_extra)
town = c.city.difference(c.sea)
town = max(town.geoms, key=lambda g: g.area) if town.geom_type == "MultiPolygon" else town
out.append(arr("dCore", [W(x, y) for x, y in town.simplify(0.6).exterior.coords]))
sea = c.sea.intersection(box(-150, -150, 750, 750)); sea = max(sea.geoms, key=lambda g: g.area) if sea.geom_type == "MultiPolygon" else sea
out.append(arr("dSea", [W(x, y) for x, y in sea.simplify(0.6).exterior.coords]))
riv = c.water_extra[0]
out.append(arr("dRiver", [W(x, y) for x, y in riv.simplify(0.4).exterior.coords]))
out.append(arr("dRiverLine", wl(NS["riv"], 2.0)))
# ---- coast road: inside the map down to its south tunnel
hw = c.highway
hcut = LineString([p for p in hw.coords if p[1] <= 625])
hp = wl(hcut, 2.0)
if hp[0][0] > hp[-1][0]: hp = hp[::-1]
out.append(arr("dCoast", hp))
out.append(f"#define WEST_PX {hp[0][0]:.2f}f\n#define WEST_PZ {hp[0][1]:.2f}f\n#define SOUTH_PX {hp[-1][0]:.2f}f\n#define SOUTH_PZ {hp[-1][1]:.2f}f\n")
# ---- streets (everything on the map except the coast road and the railway), 3 m points; bridges flagged
streets = []
for g, w, cl in c.roads:
    if cl == "rail" or g.is_empty: continue
    for gg in (g.geoms if hasattr(g, "geoms") else [g]):
        if gg.geom_type != "LineString" or gg.length < 3: continue
        streets.append((wl(gg, 3.0), w, {"st": 0, "av": 1, "stair": 2, "br": 3}.get(cl, 0)))
pts, idx = [], []
for p, w, k in streets: idx.append((len(pts), len(p), w, k)); pts += p
out.append(arr("dStreetPts", pts))
out.append("static const int dStreets[][4] = {" + ", ".join("{%d, %d, %d, %d}" % (a, b, int(round(w * 10)), k) for a, b, w, k in idx) + "};\n#define DSTREETS_N %d\n" % len(idx))
out.append("static const float dBridges[][5] = {" + ", ".join("{%.2ff, %.2ff, %.2ff, %.2ff, 7.0f}" % (W(*b.coords[0]) + W(*b.coords[-1])) for b in bridges) + "};\n#define DBRIDGES_N %d\n" % len(bridges))
# ---- railway: between its two portals, and the portals' positions and headings
ins = [t for t in np.arange(0, rail.length, 1.0) if c.city.buffer(18).contains(rail.interpolate(t))]
tA = max(min(ins), next(t for t in np.arange(0, rail.length, 1.0) if rail.interpolate(t).x < 448)); tB = max(ins)
rl = LineString([rail.interpolate(t).coords[0] for t in np.arange(tA, tB + 0.1, 1.0)])
rp = wl(rl, 2.0)
out.append(arr("dRail", rp))
out.append(f"#define RAIL_E_X {rp[0][0]:.2f}f\n#define RAIL_E_Z {rp[0][1]:.2f}f\n#define RAIL_W_X {rp[-1][0]:.2f}f\n#define RAIL_W_Z {rp[-1][1]:.2f}f\n")
sx, sz = W(*stn); out.append(f"#define STN_X {sx:.2f}f\n#define STN_Z {sz:.2f}f\n")
# ---- the pass, the old tunnel, the hamlet lane, houses along the pass, torii, the mountain
out.append(arr("dTouge", wl(c.touge, 2.0)))
tp = wl(c.touge, 2.0); mid = c.touge.interpolate(c.touge.length * 0.3); m2 = c.touge.interpolate(c.touge.length * 0.3 + 2)
dx, dy = m2.x - mid.x, m2.y - mid.y; L = math.hypot(dx, dy) or 1
lane = LineString([(mid.x, mid.y), (mid.x - dy / L * 16, mid.y + dx / L * 16)])
if c.city.buffer(4).intersects(lane): lane = LineString([(mid.x, mid.y), (mid.x + dy / L * 16, mid.y - dx / L * 16)])
out.append(arr("dLane", wl(lane, 2.0)))
hx, hz = W(*lane.coords[-1]); out.append(f"#define HAMLET_X {hx:.1f}f\n#define HAMLET_Z {hz:.1f}f\n")
ot = W(*c.oldtunnel[0].coords[0]); out.append(f"#define OLDT_X {ot[0]:.2f}f\n#define OLDT_Z {ot[1]:.2f}f\n")
mx, mz = W(c.mountain[0], c.mountain[1]); out.append(f"#define DMT_X {mx:.1f}f\n#define DMT_Z {mz:.1f}f\n#define DMT_R {c.mountain[2]:.1f}f\n")
hs = [h for h in c.houses if h.distance(lane) > 4]
out.append("static const float dHouses[][4] = {" + ", ".join("{%.1ff, %.1ff, 7.0f, 6.0f}" % W(h.centroid.x, h.centroid.y) for h in hs) + "};\n#define DHOUSES_N %d\n" % len(hs))
out.append("static const float dShrines[][2] = {{0, 0}};\n#define DSHRINES_N 0\n")
out.append(arr("dTorii", [W(x, y) for x, y in c.torii_path]))
castle = (334, 452)
tshr = [s for s in c.shrines if Point(s).distance(Point(castle)) > 5 and c.city.contains(Point(s))]
out.append(arr("dTownShrines", [W(*s) for s in tshr]))
out.append(f"#define CASTLE_X {W(*castle)[0]:.1f}f\n#define CASTLE_Z {W(*castle)[1]:.1f}f\n")
parks = [p for p in c.parks]
out.append("static const float dParks[][3] = {" + ", ".join("{%.1ff, %.1ff, %.1ff}" % (W(p.centroid.x, p.centroid.y) + (math.sqrt(p.area / math.pi),)) for p in parks) + "};\n#define DPARKS_N %d\n" % len(parks))
# ---- buildings: every drawn lot, as the largest axis-aligned rectangle inside it
roads_u = unary_union([LineString(p).buffer(w / 2) for p, w, k in streets] + [LineString(hp).buffer(4.5)])
def aa_rect(poly):
    if poly.is_empty or poly.area < 20: return None
    try: cpt = polylabel(poly, 0.3)
    except Exception: cpt = poly.representative_point()
    x0, y0, x1, y1 = poly.bounds; bw, bh = x1 - x0, y1 - y0; best = None
    for ar in (bw / bh, 1.0, 1.5, 1 / 1.5, 2.0, 0.5, 3.0, 1 / 3.0):
        lo, hi = 0.0, max(bw, bh) * 1.2
        for _ in range(18):
            m = (lo + hi) / 2; w2, h2 = (m, m / ar) if ar >= 1 else (m * ar, m)
            r = box(cpt.x - w2 / 2, cpt.y - h2 / 2, cpt.x + w2 / 2, cpt.y + h2 / 2)
            if poly.contains(r): lo = m
            else: hi = m
        w2, h2 = (lo, lo / ar) if ar >= 1 else (lo * ar, lo)
        if best is None or w2 * h2 > best[2] * best[3]: best = (cpt.x - w2 / 2, cpt.y - h2 / 2, w2, h2)
    return best
lots = []
keep_out = unary_union([Point(s).buffer(7) for s in c.shrines] + [Point(castle).buffer(18)] + [p.buffer(1) for p in parks] + [box(stn[0] - 24, stn[1] - 10, stn[0] + 24, stn[1] + 34)])
for lp in rec:
    bld = lp.buffer(-1.1, join_style=2)
    if bld.is_empty: continue
    left = bld.difference(keep_out).difference(water)
    for k in range(4):   # fill the lot with up to 4 straight buildings, largest first (stepped along curved and slanted lots)
        pieces = sorted(left.geoms, key=lambda g: -g.area) if hasattr(left, "geoms") else [left]
        placed = False
        for g in pieces:
            r = aa_rect(g)
            if r is None or r[2] < 3.4 or r[3] < 3.4: continue
            lots.append(r); left = left.difference(box(r[0] - 1.0, r[1] - 1.0, r[0] + r[2] + 1.0, r[1] + r[3] + 1.0)); placed = True; break
        if not placed or left.is_empty: break
rng = np.random.default_rng(2006)
def face_of(r):
    x, y, w, h = r; cands = [(0, (x + w / 2, y - 3)), (2, (x + w / 2, y + h + 3)), (3, (x - 3, y + h / 2)), (1, (x + w + 3, y + h / 2))]
    return min(cands, key=lambda f: roads_u.distance(Point(W(*f[1]))))[0]
L2 = []
for r in lots:
    cx, cy = r[0] + r[2] / 2, r[1] + r[3] / 2; ds = math.hypot(cx - stn[0], cy - stn[1]); area = r[2] * r[3]
    near_coast = hw.distance(Point(cx, cy)) < 40; shop_st = any(LineString(p).distance(Point(W(cx, cy))) < 14 for p, w, k in streets if k == 1)
    if ds < 70 and area > 90: kind, fl = 6, int(rng.integers(4, 8))
    elif cy < 230 and cx > 300 and area > 70: kind, fl = 1, int(rng.integers(3, 7))   # hotels and apartments on the slope
    elif near_coast or shop_st: kind, fl = 2, int(rng.integers(1, 4))
    else: kind, fl = (0, int(rng.integers(1, 3))) if rng.uniform() < 0.7 else (1, int(rng.integers(2, 4)))
    L2.append([*W(r[0], r[1]), r[2], r[3], kind, fl, face_of(r)])
# five konbini spread over the town, a koban by the station square, the station itself
cand = [i for i, l in enumerate(L2) if l[4] in (0, 2) and l[2] * l[3] > 55 and min(l[2], l[3]) > 6.5]
picked = []
for i in sorted(cand, key=lambda i: -(L2[i][2] * L2[i][3])):
    if all(math.hypot(L2[i][0] - L2[j][0], L2[i][1] - L2[j][1]) > 90 for j in picked): picked.append(i)
    if len(picked) == 5: break
for i in picked: L2[i][4], L2[i][5] = 3, 1
ks = min(range(len(L2)), key=lambda i: math.hypot(L2[i][0] + L2[i][2] / 2 - sx, L2[i][1] + L2[i][3] / 2 - (sz + 30)))
L2[ks][4], L2[ks][5] = 4, 1
L2.append([sx - 20, sz - 6, 40, 12, 5, 2, 2])   # the station, facing its square
out.append("static const float dLots[][7] = {" + ", ".join("{%.2ff, %.2ff, %.2ff, %.2ff, %d, %d, %d}" % tuple(l) for l in L2) + "};\n#define DLOTS_N %d\n" % len(L2))
sp = W(stn[0], stn[1] + 30); out.append(f"#define SPAWN_X {sp[0]:.1f}f\n#define SPAWN_Z {sp[1]:.1f}f\n")
# legacy symbols the old 5b code still names
out.append("static const float dRing0[1][2] = {{0, 0}};\n#define DRING0_N 0\nstatic const float dRing1[1][2] = {{0, 0}};\n#define DRING1_N 0\nstatic const float dRing2[1][2] = {{0, 0}};\n#define DRING2_N 0\nstatic const float dRing3[1][2] = {{0, 0}};\n#define DRING3_N 0\nstatic const float dAvenue[1][2] = {{0, 0}};\n#define DAVENUE_N 0\n")
out.append("#define NORTH_X 0.0f\n#define NORTH_Z0 0.0f\n#define NORTH_PORTAL_Z 0.0f\n#define EAST_PX SOUTH_PX\n#define EAST_PZ SOUTH_PZ\n")
open(os.environ.get("OUT_H", "zk_design.h"), "w").write("".join(out))
kinds = {}
for l in L2: kinds[l[4]] = kinds.get(l[4], 0) + 1
print("lots recorded", len(rec), "buildings", len(L2), "kinds", kinds, "streets", len(idx), "points", len(pts), "bridges", len(bridges), "rail pts", len(rp), "coast pts", len(hp), "houses", len(hs), "town shrines", len(tshr))
